INSERT INTO cht.fact_cht_values (
    uuid,
    dataset,
    data_element,
    value,
    date,
    chw_id,
    facility_id,
    district_id,
    region,
    patient_age_in_years,
    patient_age_in_months,
    patient_age_in_days,
    patient_sex,
    patient_dob,
    source_system,
    source_form
)
SELECT
    uuid AS uuid,
    'fp_registration' AS dataset,
    unpivot.data_element,
    unpivot.value,
    date,
    chw_id,
    facility_id AS facility_id,
    district_id AS district_id,
    region_id AS region,
    patient_age_in_years,
    NULL AS patient_age_in_months,
    NULL AS patient_age_in_days,
    inputs_contact_sex AS patient_sex,
    inputs_contact_date_of_birth AS patient_dob,
    'cht' AS source_system,
    'fp_registration' AS source_form
FROM (
    SELECT
        uuid,
        date,
        chw_id,
        facility_id,
        district_id,
        region_id,
        patient_age_in_years,
        inputs_contact_sex,
        inputs_contact_date_of_birth,

        -- indicator columns from MV
        current_fp_method_label,
        current_fp_method,
        chw_area_id,
        supervisor_id,
        branch_id,
        fp_next_appt_date,
        coc_given,
        condoms_given,
        pop_given,
        dmpa_given,
        contraceptives_given,
        needs_method_change,
        has_been_referred,
        fp_method,
        fp_start_date,
        who_administered_dmpa,
        condoms_received,
        enrol_on_fp_method,
        continue_current_fp_method,
        n_fp_referral_note,
        patient_referred,
        referral_follow_up_date,
        can_supply_fp_commodities,
        supply_item_name,
        supply_item_units,
        supply_limit,
        commodities_supplied_qty,
        next_appt_date,
        format_next_appt_date
    FROM cht.mv_fp_registration
) src
CROSS JOIN LATERAL (
    VALUES
        ('current_fp_method_label', src.current_fp_method_label),
        ('current_fp_method', src.current_fp_method),
        ('chw_area_id', src.chw_area_id),
        ('supervisor_id', src.supervisor_id),
        ('branch_id', src.branch_id),
        ('fp_next_appt_date', src.fp_next_appt_date),
        ('coc_given', src.coc_given),
        ('condoms_given', src.condoms_given),
        ('pop_given', src.pop_given),
        ('dmpa_given', src.dmpa_given),
        ('contraceptives_given', src.contraceptives_given),
        ('needs_method_change', src.needs_method_change),
        ('has_been_referred', src.has_been_referred),
        ('fp_method', src.fp_method),
        ('fp_start_date', src.fp_start_date),
        ('who_administered_dmpa', src.who_administered_dmpa),
        ('condoms_received', src.condoms_received),
        ('enrol_on_fp_method', src.enrol_on_fp_method),
        ('continue_current_fp_method', src.continue_current_fp_method),
        ('n_fp_referral_note', src.n_fp_referral_note),
        ('patient_referred', src.patient_referred),
        ('referral_follow_up_date', src.referral_follow_up_date),
        ('can_supply_fp_commodities', src.can_supply_fp_commodities),
        ('supply_item_name', src.supply_item_name),
        ('supply_item_units', src.supply_item_units),
        ('supply_limit', src.supply_limit),
        ('commodities_supplied_qty', src.commodities_supplied_qty),
        ('next_appt_date', src.next_appt_date),
        ('format_next_appt_date', src.format_next_appt_date)
) AS unpivot(data_element, value)
WHERE unpivot.value IS NOT NULL
  AND TRIM(unpivot.value) <> '';