INSERT INTO cht.fact_cht_values (
    uuid,
    dataset,
    data_element,
    value,
    date,
    chw_id,
    facility_id,
    district_id,
    region,
    patient_age_in_years,
    patient_age_in_months,
    patient_age_in_days,
    patient_sex,
    patient_dob,
    source_system,
    source_form
)
SELECT
    doc_id AS uuid,
    'pnc_danger_sign' AS dataset,
    unpivot.data_element,
    unpivot.value,
    date,
    chw_id,
    facility_id,
    district AS district_id,
    region,
    patient_age_in_years,
    patient_age_in_months,
    patient_age_in_days,
    patient_gender AS patient_sex,
    contact_date_of_birth as patient_dob,
    'cht' AS source_system,
    'pnc_danger_sign' AS source_form
FROM (
    SELECT
        doc_id,
        date,
        chw_id,
        facility_id,
        district,
        region,
        patient_age_in_years,
        patient_age_in_months,
        patient_age_in_days,
        patient_gender,
        contact_date_of_birth,

        -- indicator columns from MV
        is_of_child_bearing_age,
        visited_contact_uuid,
        patient_age_display,
        patient_id,
        patient_name,
        patient_name_with_s,
        visited_health_facility,
        still_experiencing_danger_signs,
        note_monitor_till_next_pnc_check_up,
        note_still_experiencing_danger_signs,
        note_danger_signs,
        excessive_bleeding,
        vaginal_discharge,
        severe_abdominal_pain,
        swelling,
        blurred_vision,
        fever,
        excessive_tiredness,
        breathlessness,
        has_danger_signs,
        has_no_danger_signs,
        note_refer,
        referred_to_facility
    FROM cht.mv_pnc_danger_sign
) src
CROSS JOIN LATERAL (
    VALUES
        ('is_of_child_bearing_age', src.is_of_child_bearing_age),
        ('visited_contact_uuid', src.visited_contact_uuid),
        ('patient_age_display', src.patient_age_display),
        ('patient_id', src.patient_id),
        ('patient_name', src.patient_name),
        ('patient_name_with_s', src.patient_name_with_s),
        ('visited_health_facility', src.visited_health_facility),
        ('still_experiencing_danger_signs', src.still_experiencing_danger_signs),
        ('note_monitor_till_next_pnc_check_up', src.note_monitor_till_next_pnc_check_up),
        ('note_still_experiencing_danger_signs', src.note_still_experiencing_danger_signs),
        ('note_danger_signs', src.note_danger_signs),
        ('excessive_bleeding', src.excessive_bleeding),
        ('vaginal_discharge', src.vaginal_discharge),
        ('severe_abdominal_pain', src.severe_abdominal_pain),
        ('swelling', src.swelling),
        ('blurred_vision', src.blurred_vision),
        ('fever', src.fever),
        ('excessive_tiredness', src.excessive_tiredness),
        ('breathlessness', src.breathlessness),
        ('has_danger_signs', src.has_danger_signs),
        ('has_no_danger_signs', src.has_no_danger_signs),
        ('note_refer', src.note_refer),
        ('referred_to_facility', src.referred_to_facility)
) AS unpivot(data_element, value)
WHERE unpivot.value IS NOT NULL
  AND TRIM(unpivot.value) <> '';