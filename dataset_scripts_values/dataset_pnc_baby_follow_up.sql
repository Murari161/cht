        ('contact_id', src.contact_id),
        ('contact_name', src.contact_name),
        ('contact_date_of_birth', src.contact_date_of_birth),
        ('contact_sex', src.contact_sex),
        ('has_danger_signs', src.has_danger_signs),
        ('pnc_visit_label', src.pnc_visit_label),
        ('chw_name', src.chw_name),
