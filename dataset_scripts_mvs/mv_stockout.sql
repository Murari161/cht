CREATE MATERIALIZED VIEW cht.mv_stockout
TABLESPACE ts_report
AS
SELECT
    doc ->> '_id'::text                              AS doc_id,
    doc ->> '_rev'::text                             AS rev,                                 -- [NEW FIELD]
    to_timestamp((NULLIF(doc ->> 'reported_date'::text, ''::text)::bigint / 1000)::double precision) AS reported,
    (TO_CHAR(TO_TIMESTAMP((doc->>'reported_date')::BIGINT / 1000), 'YYYY-MM-DD'))::date AS date,
    (TO_CHAR(TO_TIMESTAMP((doc->>'reported_date')::BIGINT / 1000), 'YYYY'))::INT AS year,
    TO_CHAR(TO_TIMESTAMP((doc->>'reported_date')::BIGINT / 1000), 'FMMonth') AS month,
    doc ->'fields'->'meta'->>'instanceID' AS instanceID,
    doc ->'fields'->'inputs'->'meta'->>'deprecatedID' AS deprecatedID,
    doc ->'fields'->'inputs'->'meta'->'location'->>'lat' AS location_lat,
    doc ->'fields'->'inputs'->'meta'->'location'->>'long' AS location_long,
    doc ->'fields'->'inputs'->'meta'->'location'->>'error' AS location_error,
    doc ->'fields'->'inputs'->'meta'->'location'->>'message' AS location_message,
    doc ->'geolocation'->>'code' AS geolocation_code,
    doc ->'geolocation'->>'message' AS geolocation_message,
    doc ->> 'from'::text                             AS  from,

    doc #>> '{fields,inputs,source}'::text[]                          AS source,
    doc #>> '{fields,inputs,source_id}'::text[]                       AS source_id,
    (doc #>> '{fields,inputs,act_stock_value}')::int                AS act_stock_value,
    (doc #>> '{fields,inputs,gloves_stock_value}')::int                AS gloves_stock_value,
    (doc #>> '{fields,inputs,zinc_stock_value}')::int                 AS zinc_stock_value,
    (doc #>> '{fields,inputs,amoxicillin_stock_value}')::int           AS amoxicillin_stock_value,
    (doc #>> '{fields,inputs,malaria_rdts_stock_value}')::int          AS malaria_rdts_stock_value,
    (doc #>> '{fields,inputs,pop_stock_value}')::int                   AS pop_stock_value,
    (doc #>> '{fields,inputs,dmpa_stock_value}')::int                 AS dmpa_stock_value,
    (doc #>> '{fields,inputs,misoprostol_stock_value}')::int           AS misoprostol_stock_value,
    (doc #>> '{fields,inputs,coc_stock_value}')::int                   AS coc_stock_value,
    (doc #>> '{fields,inputs,condoms_stock_value}')::int               AS condoms_stock_value,
    (doc #>> '{fields,inputs,contraceptives_stock_value}')::int        AS contraceptives_stock_value,
    (doc #>> '{fields,inputs,rectal_stock_value}')::int               AS rectal_stock_value,
    (doc #>> '{fields,inputs,sayana_stock_value}')::int                AS sayana_stock_value,
    doc #>> '{fields,inputs,contact,_id}'::text[]                     AS contact_id,
    doc #>> '{fields,inputs,contact,name}'::text[]                    AS contact_name,
    doc #>> '{fields,inputs,contact,contact,name}'::text[]            AS nested_contact_name,
    doc #>> '{fields,place_id}'::text[]                                AS place_id,
    doc #>> '{fields,private}'::text[]                                 AS private,
    doc #>> '{fields,place_name}'::text[]                              AS place_name,
    doc #>> '{fields,vht_name}'::text[]                                 AS vht_name,
    doc #>> '{fields,act_low}'::text[]                                  AS act_low,
    doc #>> '{fields,amoxicillin_low}'::text[]                          AS amoxicillin_low,
    doc #>> '{fields,zinc_low}'::text[]                                 AS zinc_low,
    doc #>> '{fields,condoms_low}'::text[]                              AS condoms_low,
    doc #>> '{fields,rdts_low}'::text[]                                 AS rdts_low,
    doc #>> '{fields,coc_low}'::text[]                                  AS coc_low,
    doc #>> '{fields,pop_low}'::text[]                                  AS pop_low,
    doc #>> '{fields,contraceptives_low}'::text[]                       AS contraceptives_low,
    doc #>> '{fields,dmpa_low}'::text[]                                 AS dmpa_low,
    doc #>> '{fields,rectal_low}'::text[]                                AS rectal_low,
    doc #>> '{fields,gloves_low}'::text[]                                AS gloves_low,
    doc #>> '{fields,vht_stock_details,note_low_stock}'::text[]            AS note_low_stock,
    doc #>> '{fields,vht_stock_details,act_at_hand}'::text[]               AS act_at_hand,
    doc #>> '{fields,vht_stock_details,mrdt_at_hand}'::text[]              AS mrdt_at_hand,
    doc #>> '{fields,vht_stock_details,rectal_at_hand}'::text[]            AS rectal_at_hand,
    doc #>> '{fields,vht_stock_details,gloves_at_hand}'::text[]            AS gloves_at_hand,
    doc #>> '{fields,vht_stock_details,zinc_at_hand}'::text[]              AS zinc_at_hand,
    doc #>> '{fields,vht_stock_details,amoxicillin_at_hand}'::text[]      AS amoxicillin_at_hand,
    doc #>> '{fields,vht_stock_details,pop_at_hand}'::text[]               AS pop_at_hand,
    doc #>> '{fields,vht_stock_details,coc_at_hand}'::text[]               AS coc_at_hand,
    doc #>> '{fields,vht_stock_details,contraceptives_at_hand}'::text[]   AS contraceptives_at_hand,
    doc #>> '{fields,vht_stock_details,dmpa_at_hand}'::text[]              AS dmpa_at_hand,
    doc #>> '{fields,vht_stock_details,condom_at_hand}'::text[]            AS condom_at_hand,
    doc #>> '{fields,vht_stock_details,action,note_replenish_stock}'::text[]    AS action_note_replenish_stock,
    doc #>> '{fields,vht_stock_details,action,action_taken}'::text[]           AS action_taken,
    doc #>> '{fields,vht_stock_details,action,other_action_taken}'::text[]     AS action_other_action_taken,
    doc #>> '{fields,vht_stock_details,action,issued_stock_note}'::text[]      AS action_issued_stock_note,

    doc #>> '{fields,summary,r_summary}'::text[]                           AS r_summary,
    doc #>> '{fields,summary,s_submit}'::text[]                             AS s_submit,
    doc #>> '{fields,summary,note_finding}'::text[]                         AS note_finding,
    doc #>> '{fields,summary,act_finding}'::text[]                          AS act_finding,
    doc #>> '{fields,summary,rdts_finding}'::text[]                         AS rdts_finding,
    doc #>> '{fields,summary,rectal_finding}'::text[]                       AS rectal_finding,
    doc #>> '{fields,summary,gloves_finding}'::text[]                        AS gloves_finding,
    doc #>> '{fields,summary,zinc_finding}'::text[]                          AS zinc_finding,
    doc #>> '{fields,summary,amoxicillin_finding}'::text[]                   AS amoxicillin_finding,
    doc #>> '{fields,summary,pop_finding}'::text[]                            AS pop_finding,
    doc #>> '{fields,summary,coc_finding}'::text[]                            AS coc_finding,
    doc #>> '{fields,summary,contraceptives_finding}'::text[]                AS contraceptives_finding,
    doc #>> '{fields,summary,dmpa_finding}'::text[]                           AS dmpa_finding,
    doc #>> '{fields,summary,condoms_finding}'::text[]                        AS condoms_finding,
    doc #>> '{fields,summary,action_taken_summary}'::text[]                   AS action_taken_summary,
    doc #>> '{fields,summary,action_taken_summary_vht_given}'::text[]        AS action_taken_summary_vht_given,
    doc #>> '{fields,summary,action_taken_summary_no_taken}'::text[]         AS action_taken_summary_no_taken,
    doc #>> '{fields,summary,action_taken_summary_vht_taken}'::text[]        AS action_taken_summary_vht_taken,
    doc #>> '{fields,summary,taken_other}'::text[]                             AS taken_other,
    doc #>> '{fields,summary,s_followup}'::text[]                              AS s_followup,
    doc #>> '{fields,summary,s_followup_note}'::text[]                         AS s_followup_note,

    --- reporting hierarchy
    doc #>> '{contact,_id}'                         AS chw_id,                   
    doc #>> '{contact,parent,_id}'                  AS chw_area_id,  
    doc #>> '{contact,parent,parent,_id}'           AS facility_id,                                    
    doc #>> '{contact,parent,parent,parent,_id}'    AS parish_id,              
    doc #>> '{contact,parent,parent,parent,parent,_id}'           AS district,                 
    doc #>> '{contact,parent,parent,parent,parent,parent,_id}'    AS region,
    CURRENT_TIMESTAMP                                 AS last_refresh_date   


FROM dwh.cht_data
WHERE (doc ->> 'form') = 'stockout'
  AND is_current
WITH DATA;

CREATE INDEX mv_stockout_reported_idx
    ON cht.mv_stockout USING btree (reported);
